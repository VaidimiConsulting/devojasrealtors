const express = require('express');
const router = express.Router();
const {
  getDashboardStats, getMyTeam, getMyCommissions, getMySales, getMyWallet, requestWithdrawal,
  browsePlots, updateProfile, changePassword, submitKyc,
  getMyNotifications, markNotificationRead, createComplaint, getMyComplaints,
  createTeamMember, getMyNetwork, getMyPlots, getMyRewards, recordPaymentForDeal,
  getDownlineCommissions, getDownlineMembers, setTeamMemberCommission
} = require('../controllers/associateController');
const { protect, authorize } = require('../middleware/auth');

// Every route here is protected AND restricted to role = 'associate'
router.use(protect, authorize('associate'));

router.get('/dashboard-stats', getDashboardStats);
router.get('/my-team', getMyTeam);
router.post('/team', createTeamMember);
// NOTE: commission update is ADMIN-only — associates cannot change commission %
router.get('/network', getMyNetwork);
router.get('/commissions', getMyCommissions);
router.get('/sales', getMySales);
router.get('/my-plots', getMyPlots);
router.get('/my-rewards', getMyRewards);

// Downline commission tracking (hierarchy-isolated — server side)
router.get('/downline-commissions', getDownlineCommissions);
router.get('/downline-members', getDownlineMembers);

router.get('/wallet', getMyWallet);
router.post('/withdraw', requestWithdrawal);
router.post('/transactions/:id/payments', recordPaymentForDeal);

// Receipt Download (Protected with associate ownership check in controller)
const { downloadPaymentReceiptPdf, downloadTransactionReceiptPdf } = require('../controllers/accountsController');
router.get('/payments/:id/receipt-pdf', downloadPaymentReceiptPdf);
router.get('/transactions/:id/receipt-pdf', downloadTransactionReceiptPdf);

// Plot purchasing for associates (reuses same plotController as admin, access restricted by role middleware here)
// SECURITY FIX: previously this reused the admin company-acquisition handler (plotController.purchasePlot),
// which let an associate add plots into company inventory. Associates now submit plot SALES (booking forms)
// with a validated Referral ID; commission is generated by the shared commission engine.
const { createBookingForm } = require('../controllers/bookingFormController');
const { getPlotPurchases } = require('../controllers/plotController');
router.post('/plot-purchases', createBookingForm);
router.get('/plot-purchases', getPlotPurchases);

router.get('/plots', browsePlots);

router.put('/profile', updateProfile);
router.put('/change-password', changePassword);
router.post('/kyc', submitKyc);

router.get('/notifications', getMyNotifications);
router.put('/notifications/:id/read', markNotificationRead);

router.post('/complaints', createComplaint);
router.get('/complaints', getMyComplaints);

module.exports = router;

